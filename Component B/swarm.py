# Robot Starting Positions (World X, World Y)
robots = {
    "robot_1": (-2.0, -3.0),
    "robot_2": (4.0, 0.0),
    "robot_3": (0.5, 5.0),
}

# PSO Settings
NUM_PARTICLES = 30
ITERATIONS = 100
INERTIA = 0.7
COGNITIVE = 1.5
SOCIAL = 1.5

# Fitness Weights
ROUTE_DISTANCE_WEIGHT = 1.0
START_DISTANCE_REWARD_WEIGHT = 0.35
SEPARATION_PENALTY_WEIGHT = 2.0
BOUNDARY_PENALTY_WEIGHT = 1.5
REGION_COVERAGE_WEIGHT = 3.0

# Arena and Route Planning Settings
TARGETS_PER_ROBOT = 8
ARENA_HALF_SIZE = 7.0
PREFERRED_BOUNDARY_LIMIT = 5.0
MIN_TARGET_SEPARATION = 1.5

random.seed(42)

# Distance Function
def distance(point_a, point_b):
    """
    Calculating the Euclidean Distance between 2 (x, y) points
    """
    return math.hypot(point_a[0] - point_b[0], point_a[1] - point_b[1])

def load_targets():
    """
    Importing valid candidate locations generated by target_visualization.py.
    """
    from target_visualization import generate_targets, get_obstacle_polygon, obstacles

    polygons = [get_obstacle_polygon(obstacle) for obstacle in obstacles]

    candidate_targets = generate_targets(polygons)

    required_targets = len(robots) * TARGETS_PER_ROBOT

    if len(candidate_targets) < required_targets:
        raise ValueError(
            f"Not enough valid candidate targets for all robots."
            f"Need at least {len(robots) * TARGETS_PER_ROBOT} candidate targets."
        )

    return candidate_targets

# Representation of the Particles
class Particle:
    """
    One candidate solution is selected which contains a target index for every route waypoint.
    """
    def __init__(self, dimensions, num_targets):
        self.position = [random.uniform(0, num_targets - 1) for _ in range(dimensions)]
        self.velocity = [random.uniform(-1, 1) for _ in range(dimensions)]

        # Personal Best
        self.best_position = self.position.copy()
        self.best_fitness = float("inf")

# Particle Swarm Optimization
class PSO:
    def __init__(
            self,
            robot_positions,
            candidate_targets,
            num_particles=NUM_PARTICLES,
            iterations=ITERATIONS,
            inertia=INERTIA,
            cognitive=COGNITIVE,
            social=SOCIAL
    ):
        self.robot_names = list(robot_positions.keys())
        self.robot_positions = list(robot_positions.values())
        self.targets = candidate_targets
        self.targets_per_robot = TARGETS_PER_ROBOT
        self.dimensions = len(self.robot_names) * self.targets_per_robot

        self.num_particles = num_particles
        self.iterations = iterations
        self.inertia = inertia
        self.cognitive = cognitive
        self.social = social

        self.particles = [
            Particle(self.dimensions, len(self.targets))

            for _ in range(self.num_particles)
        ]

        # Setting the Global Best
        self.global_best_position = None
        self.global_best_fitness = float("inf")
        self.convergence = []

    def decode_position(self, position):
        """
        Converting continuous particle values into unique candidate target indices.
        """
        target_indices = []
        avail_indices = set(range(len(self.targets)))

        # Prefer the closest unused target index for each robot.
        for value in position:
            # Avoiding sorting the entire candidate list for every dimension
            chosen = min(avail_indices, key=lambda index: abs(index - value))

            target_indices.append(chosen)
            avail_indices.remove(chosen)

        return target_indices

    def decode_routes(self, position):
        """
        Return a route (ordered list of target coordinates) for each robot.
        """
        indices = self.decode_position(position)
        routes = {}
        offset = 0

        for robot_name in self.robot_names:
            robot_indices = indices[offset:offset + self.targets_per_robot]

            routes[robot_name] = [self.targets[index] for index in robot_indices]

            offset += self.targets_per_robot

        return routes

    @staticmethod
    def boundary_penalty(target):
        x, y = target
        excess_x = max(0.0, abs(x) - PREFERRED_BOUNDARY_LIMIT)
        excess_y = max(0.0, abs(y) - PREFERRED_BOUNDARY_LIMIT)
        available_margin = max(ARENA_HALF_SIZE - PREFERRED_BOUNDARY_LIMIT, 0.001)

        return (excess_x + excess_y) / available_margin

    def fitness(self, position):
        """
        Evaluate a complete multi-waypoint plan.

        The score balances route length, an initial distance incentive, separation between assigned targets. boundary
        clearance, and distribution across the arena's four broad quadrants
        """
        routes = self.decode_routes(position)

        total_route_distance = 0.0
        initial_distance_reward = 0.0
        all_targets = []

        for robot_name, route in routes.items():
            current = robots[robot_name]

            if route:
                # Encourages the first target to be meaningfully away from the start.
                max_arena_distance = math.hypot(2 * ARENA_HALF_SIZE, 2 * ARENA_HALF_SIZE)

                initial_distance_reward += distance(current, route[0]) / max_arena_distance

            for target in route:
                total_route_distance += distance(current, target)
                current = target
                all_targets.append(target)

        # Penalize waypoint pairs that are almost duplicates.
        separation_penalty = 0.0

        for i in range(len(all_targets)):
            for j in range(i + 1, len(all_targets)):
                separation = distance(all_targets[i], all_targets[j])

                if separation < MIN_TARGET_SEPARATION:
                    separation_penalty += (MIN_TARGET_SEPARATION - separation) / MIN_TARGET_SEPARATION

        boundary_penalty = sum(self.boundary_penalty(t) for t in all_targets)

        # Reward using distinct broad regions, it ultimately doesn't assign robots to fixed regions.
        occupied_quads = set()

        for x, y in all_targets:
            occupied_quads.add((1 if x >= 0 else -1, 1 if y >= 0 else -1))

        missing_quads = 4 - len(occupied_quads)

        return (
            ROUTE_DISTANCE_WEIGHT * total_route_distance
            - START_DISTANCE_REWARD_WEIGHT * initial_distance_reward
            + SEPARATION_PENALTY_WEIGHT * separation_penalty
            + BOUNDARY_PENALTY_WEIGHT * boundary_penalty
            + REGION_COVERAGE_WEIGHT * missing_quads
        )

    def optimize(self):
        """
        Run PSO and return the best multi-target routes per robot.
        """
        for particle in self.particles:
            fitness_value = self.fitness(particle.position)

            particle.best_fitness = fitness_value
            particle.best_position = particle.position.copy()

            if fitness_value < self.global_best_fitness:
                self.global_best_fitness = fitness_value
                self.global_best_position = particle.position.copy()

        # Run PSO Iterations
        for iteration in range(self.iterations):
            for particle in self.particles:
                for dimension in range(self.dimensions):
                    r1 = random.random()
                    r2 = random.random()

                    cognitive_velocity = (
                        self.cognitive * r1 * (particle.best_position[dimension] - particle.position[dimension])
                    )

                    social_velocity = (
                        self.social * r2 * (self.global_best_position[dimension] - particle.position[dimension])
                    )

                    particle.velocity[dimension] = (
                        self.inertia * particle.velocity[dimension] + cognitive_velocity + social_velocity
                    )

                    particle.position[dimension] = max(
                        0.0,
                        min(
                            len(self.targets) - 1,
                            particle.position[dimension] + particle.velocity[dimension]
                        )
                    )

                current_fitness = self.fitness(particle.position)

                if current_fitness < particle.best_fitness:
                    particle.best_fitness = current_fitness
                    particle.best_position = particle.position.copy()

                if current_fitness < self.global_best_fitness:
                    self.global_best_fitness = current_fitness
                    self.global_best_position = particle.position.copy()

            self.convergence.append(self.global_best_fitness)

            print(
                f"Iteration {iteration + 1:03d} | "
                f"Best Route Fitness: {self.global_best_fitness:.3f}"
            )

        return self.decode_routes(self.global_best_position)

# A* Integration
def plan_full_routes(routes, candidate_targets):
    """
    Using A* Algorithm created in path_planning.py to create a collision-free path from each robot's starting position
    through each of their assigned PSO targets.

    Returns full paths containing the intermediate A* nodes.
    """
    full_paths = {}

    for robot_name, targets in routes.items():
        current_position = robots[robot_name]
        full_path = [current_position]

        print(f"\nPlanning Safe Path For {robot_name}...")

        for sequence, target in enumerate(targets, start=1):
            print(f"Target {sequence}: {target}")
            print(f"In Candidate Targets: {target in candidate_targets}")

            segment = astar(current_position, target)

            if segment is None:
                raise ValueError(
                    f"A* couldn't find a path for {robot_name} from {current_position} to target {sequence}: "
                    f"{target}"
                )

            # Avoid duplicating the joining point between segments.
            full_path.extend(segment[1:])

            current_position = target

        full_paths[robot_name] = full_path

        print(
            f"{robot_name}: {len(targets)} targets, "
            f"{len(full_path)} path points"
        )

    return full_paths

# Saving Results
def save_convergence(convergence):
    output_file = DATA_DIR / "pso_convergence.csv"

    with output_file.open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(["iteration", "best_route_fitness"])

        for iteration, fitness_value in enumerate(convergence, start=1):
            writer.writerow([iteration, fitness_value])

    print(f"\nConvergence Data Saved To: {output_file}")

def save_routes(routes):
    """
    Saving a CSV file for analysis and a JSON route file to be used when integrating with the controller.
    """
    csv_file = DATA_DIR / "pso_routes.csv"

    with csv_file.open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(["robot", "sequence", "target_x", "target_y"])

        for robot_name, route in routes.items():
            for sequence, (x, y) in enumerate(route, start=1):
                writer.writerow([robot_name, sequence, x, y])

    json_file = DATA_DIR / "pso_routes.json"

    with json_file.open("w", encoding="utf-8") as file:
        json.dump(
            {
                name: [[float(x), float(y)] for x, y in route]

                for name, route in routes.items()
            },
            file,
            indent=2
        )

    print(f"Route CSV Saved To: {csv_file}")
    print(f"Route JSON Saved To: {json_file}")

def save_full_paths(full_paths):
    """
    Saving complete A* paths for Webots Controller Integration.
    """
    json_file = DATA_DIR / "astar_full_paths.json"

    with json_file.open("w", encoding="utf-8") as file:
        json.dump(
            {
                name: [[float(x), float(y)] for x, y in path]

                for name, path in full_paths.items()
            },
            file,
            indent=2
        )

    print(f"Full A* Paths Saved To: {json_file}")

# Visualizing Results
def plot_convergence(convergence):
    plt.figure(figsize=(10, 10))

    plt.plot(
        range(1, len(convergence) + 1),
        convergence,
        label="Global Best Fitness"
    )

    plt.xlabel("Iteration")
    plt.ylabel("Best Route Fitness (Lower is Better)")
    plt.title("PSO Route-Planning Convergence")
    plt.grid(True)
    plt.legend()

    plt.tight_layout()

    output_file = RESULTS_DIR / "pso_convergence.png"
    plt.savefig(output_file, dpi=200)

    plt.show()

    print(f"Convergence Plot Saved To: {output_file}")


def plot_routes(routes, candidate_targets, full_paths):
    """
    Visualizing PSO Target Assignments and complete A* paths.
    """
    from target_visualization import obstacles, get_obstacle_polygon

    fig, ax = plt.subplots(figsize=(12, 10))

    # Displaying all valid candidate targets
    target_x = [point[0] for point in candidate_targets]
    target_y = [point[1] for point in candidate_targets]

    plt.scatter(
        target_x,
        target_y,
        s=8,
        alpha=0.18,
        color="grey",
        label="Valid Candidate Targets",
        zorder=1
    )

    # Displaying obstacles using their projected floor polygons.
    for index, obstacle in enumerate(obstacles, start=1):
        polygon = get_obstacle_polygon(obstacle)

        poly_x = [point[0] for point in polygon]
        poly_y = [point[1] for point in polygon]

        # Closing the polygon for drawing
        poly_x.append(poly_x[0])
        poly_y.append(poly_y[0])

        ax.fill(
            poly_x,
            poly_y,
            color="black",
            alpha=0.65,
            label="Obstacles" if index == 1 else None,
            zorder=2
        )

    # Plotting each robot's full A* path and assigned PSO targets.
    for robot_name, start in robots.items():
        assigned_targets = routes[robot_name]

        path = full_paths[robot_name]

        # Complete Path including all A* nodes without the labels
        path_x = [point[0] for point in path]
        path_y = [point[1] for point in path]

        ax.plot(
            path_x,
            path_y,
            "-",
            lw=1.5,
            alpha=0.8,
            label=f"{robot_name} A* Path",
            zorder=3
        )

        # Robot's stating position
        ax.scatter(
            *start,
            marker="s",
            s=110,
            edgecolors="black",
            label=f"{robot_name} start",
            zorder=5
        )

        target_x = [point[0] for point in assigned_targets]
        target_y = [point[1] for point in assigned_targets]

        ax.scatter(
            target_x,
            target_y,
            marker="o",
            s=45,
            edgecolors="black",
            lw=0.5,
            zorder=6
        )

        for sequence, (x, y) in enumerate(assigned_targets, start=1):
            plt.annotate(
                f"T{sequence}",
                (x, y),
                xytext=(4, 4),
                textcoords="offset points",
                fontsize=8,
                zorder=7
            )

    plt.xlabel("World X (m)")
    plt.ylabel("World Y (m)")
    plt.title("PSO Target Allocation and A* Multi-Robot Paths")
    plt.xlim(-ARENA_HALF_SIZE, ARENA_HALF_SIZE)
    plt.ylim(-ARENA_HALF_SIZE, ARENA_HALF_SIZE)
    plt.gca().set_aspect("equal", adjustable="box")
    plt.grid(True, alpha=0.3)
    plt.legend(fontsize=8, loc="upper left", bbox_to_anchor=(1.02, 1))

    plt.tight_layout()

    output_file = RESULTS_DIR / "pso_routes.png"
    plt.savefig(output_file, dpi=200, bbox_inches="tight")

    plt.show()

    print(f"Route Plot Saved To: {output_file}")

def main():
    candidate_targets = load_targets()

    print(f"Loaded {len(candidate_targets)} valid candidate targets.")
    print(f"Planning {TARGETS_PER_ROBOT} targets for each of {len(robots)} robots.")

    pso = PSO(robots, candidate_targets)
    routes = pso.optimize()

    # Converting the PSO target assignments into A* paths
    full_paths = plan_full_routes(routes, candidate_targets)

    print("\nFinal Target Sequences:")

    for robot_name, route in routes.items():
        print(f"\n{robot_name}, start={robots[robot_name]}")

        for sequence, target in enumerate(route, start=1):
            print(f"Target {sequence}: ({target[0]:.2f}, {target[1]:.2f})")

    print(f"\nBest Route Fitness: {pso.global_best_fitness:.3f}")

    save_convergence(pso.convergence)

    # Saving the assigned PSO targets for analysis
    save_routes(routes)

    # Saving the complete A* paths for later Webots integration
    save_full_paths(full_paths)

    # Generative Visualization
    plot_convergence(pso.convergence)
    plot_routes(routes, candidate_targets, full_paths)

if __name__ == "__main__":
    main()